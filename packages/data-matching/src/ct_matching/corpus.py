class Rng:
    """SHA-256 counter PRNG: stable across Python versions (unlike ``random`` helper methods)."""

    def __init__(self, seed: Any) -> None:
        self.seed, self.n = str(seed), 0

    def _next(self) -> int:
        self.n += 1
        return int.from_bytes(hashlib.sha256(f"{self.seed}:{self.n}".encode()).digest()[:8], "big")

    def below(self, n: int) -> int:
        return self._next() % n

    def chance(self, p: float) -> bool:
        return self._next() / 2 ** 64 < p

    def choice(self, seq: Sequence[Any]) -> Any:
        return seq[self.below(len(seq))]

    def sample(self, seq: Sequence[Any], k: int) -> list[Any]:
        pool = list(seq)
        k = min(k, len(pool))
        for i in range(k):
            j = i + self.below(len(pool) - i)
            pool[i], pool[j] = pool[j], pool[i]
        return pool[:k]

    def weighted(self, pairs: Sequence[tuple[Any, int]]) -> Any:
        pick = self.below(sum(w for _, w in pairs))
        for item, weight in pairs:
            pick -= weight
            if pick < 0:
                return item
        raise AssertionError("unreachable")


def _iso(dt: datetime) -> str:
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


def _ts(text: str) -> datetime:
    return datetime.strptime(text, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)


def _employers(count: int) -> list[dict[str, Any]]:
    out = []
    for i in range(count):
        w1, w2 = _W1[i % len(_W1)], _W2[(i // len(_W1) + i) % len(_W2)]
        suffix = "" if i < len(_W1) * len(_W2) else f" {i}"
        name = f"Fictional {w1} {w2}{suffix}"
        slug = f"fictional-{w1}-{w2}{suffix.strip()}".lower()
        out.append({"name": name, "board": slug.replace("-", ""), "domain": f"jobs.{slug}.example",
                    "ats": _ATS[i % len(_ATS)], "org_uid": f"org-syn-{i:04d}"})
    return out


def _surface(rng: Rng, skill: str) -> str:
    return rng.choice((skill.replace("-", " "),) + taxonomy.SKILLS[skill])


def _latent(rng: Rng, idx: int, employers: list[dict[str, Any]], as_of: datetime) -> dict[str, Any]:
    family = rng.weighted(_FAMILY_WEIGHTS)
    spec = taxonomy.FAMILIES[family]
    level = "director" if family == "field-cto" else rng.choice(_LEVELS)
    if family == "engineering-manager":
        level = rng.choice(("senior", "staff", "director"))
    required = rng.sample(spec["core"], 3 + rng.below(max(1, len(spec["core"]) - 2))) + rng.sample(spec["optional"], 1 + rng.below(2))
    preferred = [s for s in rng.sample(spec["optional"], 2 + rng.below(2)) if s not in required]
    if rng.chance(0.2):
        required.append(rng.choice([s for s in taxonomy.SKILL_IDS if s not in required]))
    location, country = rng.choice(_LOCATIONS)
    remote = rng.choice(_REMOTE)
    pay = None
    if rng.chance(0.55):
        base = _PAY_BASE[level] + rng.below(30)
        currency = "USD" if country in ("US", None) else {"GB": "GBP", "DE": "EUR", "IE": "EUR", "CA": "CAD"}[country]
        pay = {"min": base * 1000, "max": (base + 20 + rng.below(40)) * 1000, "currency": currency, "period": "year",
               "style": rng.choice(("structured", "structured", "text", "both"))}
    employer = rng.choice(employers)
    title = _LEVEL_WORD[level] + rng.choice(_TITLES[family]) if family != "field-cto" else "Field CTO"
    proximity = spec["customer"]
    duties = []
    if proximity >= 0.6:
        duties += rng.sample(_DUTIES["customer"], 2)
    if spec["enterprise"] >= 0.7:
        duties += rng.sample(_DUTIES["enterprise"], 1 + rng.below(2))
    duties += rng.sample(_DUTIES["internal"], 2)
    return {"key": f"syn-{idx:05d}", "family": family, "seniority": level, "title": title, "employer": employer,
            "required": sorted(set(required)), "preferred": sorted(set(preferred)), "location": location,
            "country": country, "remote": remote, "pay": pay, "duties": duties,
            "posted_at": _iso(as_of - timedelta(days=3 + rng.below(110), hours=rng.below(24))),
            "employment": rng.choice(("Full-time", "Full-time", "Full-time", "Full-time", "Contract", None)),
            "tags": [], "active": True, "extra_html": "", "expires_at": None}


def _description(rng: Rng, lat: dict[str, Any]) -> str:
    def bullets(skills: Sequence[str]) -> str:
        return "".join(f"<li>Experience with {html.escape(_surface(rng, s))}</li>" for s in skills)

    parts = [f"<p><em>{NOTICE}</em></p>", "<h3>About the role</h3>",
             "".join(f"<p>{html.escape(d)}</p>" for d in lat["duties"]),
             "<h3>Requirements</h3><ul>" + bullets(lat["required"]) + "</ul>"]
    if lat["preferred"]:
        parts.append("<h3>Nice to have</h3><ul>" + bullets(lat["preferred"]) + "</ul>")
    pay = lat["pay"]
    if pay and pay["style"] in ("text", "both") and not pay.get("text_override"):
        parts.append(f"<h3>Compensation</h3><p>{pay['currency']} {pay['min']:,} - {pay['max']:,} per year</p>")
    if pay and pay.get("text_override"):
        parts.append(f"<h3>Compensation</h3><p>{html.escape(pay['text_override'])}</p>")
    parts.append(lat["extra_html"])
    parts.append("<h3>Benefits</h3><p>Fictional benefits. Equal opportunity statement placeholder.</p>")
    return "".join(parts)


def _structured_pay(lat: dict[str, Any]) -> dict[str, Any] | None:
    pay = lat["pay"]
    if not pay or pay["style"] not in ("structured", "both"):
        return None
    return {"min": pay.get("s_min", pay["min"]), "max": pay.get("s_max", pay["max"]), "currency": pay["currency"],
            "period": pay["period"]}


def _url(lat: dict[str, Any]) -> str:
    return lat.get("url_override") or f"https://{lat['employer']['domain']}/positions/{lat['key']}"


def _loc_string(lat: dict[str, Any]) -> str | None:
    if lat.get("location_override") is not None:
        return lat["location_override"] or None
    return lat["location"]


